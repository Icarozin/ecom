// Captura UTM params da URL atual no momento do carregamento
function getTrackingParams() {
  const params = new URLSearchParams(window.location.search);
  return {
    src: params.get('src') || null,
    sck: params.get('sck') || null,
    utm_source: params.get('utm_source') || null,
    utm_campaign: params.get('utm_campaign') || null,
    utm_medium: params.get('utm_medium') || null,
    utm_content: params.get('utm_content') || null,
    utm_term: params.get('utm_term') || null
  };
}

// Armazena UTM params no localStorage ao entrar no site (para não perder ao navegar)
(function captureUtmOnLoad() {
  const params = getTrackingParams();
  const hasAny = Object.values(params).some(v => v !== null);
  if (hasAny) {
    localStorage.setItem('utmify_tracking_params', JSON.stringify(params));
  }
})();

function getSavedTrackingParams() {
  try {
    return JSON.parse(localStorage.getItem('utmify_tracking_params')) || getTrackingParams();
  } catch {
    return getTrackingParams();
  }
}

// Formata data UTC no formato esperado pela Utmify: 'YYYY-MM-DD HH:MM:SS'
function formatUtmifyDate(date) {
  const d = date || new Date();
  const pad = (n) => String(n).padStart(2, '0');
  return `${d.getUTCFullYear()}-${pad(d.getUTCMonth() + 1)}-${pad(d.getUTCDate())} ${pad(d.getUTCHours())}:${pad(d.getUTCMinutes())}:${pad(d.getUTCSeconds())}`;
}

/**
 * Envia dados de tracking para a Utmify via nosso proxy no server.
 * @param {object} params
 * @param {string} params.orderId - ID único do pedido (ex: transactionId da HubPague)
 * @param {string} params.status - 'waiting_payment' | 'paid' | 'refunded' | 'chargedback'
 * @param {string} params.createdAt - Data de criação do pedido (UTC)
 * @param {string|null} params.approvedDate - Data de aprovação (UTC) ou null
 * @param {object} params.customerData - Dados do checkout (checkoutData)
 * @param {Array} params.cartItems - Itens do carrinho
 * @param {number} params.totalPriceInCents - Valor total em centavos
 */
async function sendUtmifyTracking({ orderId, status, createdAt, approvedDate, customerData, cartItems, totalPriceInCents }) {
  try {
    const trackingParams = getSavedTrackingParams();
    
    // Estima taxa do gateway: ~1% do total (ajuste conforme taxa real da HubPague)
    const gatewayFeeInCents = Math.round(totalPriceInCents * 0.01);
    const userCommissionInCents = totalPriceInCents - gatewayFeeInCents;

    const cleanPhone = (customerData.telefone || '').replace(/\D/g, '');
    const cleanCpf = (customerData.cpf || '').replace(/\D/g, '');

    const payload = {
      orderId: orderId,
      platform: 'BotasTexanasCountry',
      paymentMethod: 'pix',
      status: status,
      createdAt: createdAt,
      approvedDate: approvedDate || null,
      refundedAt: null,
      customer: {
        name: customerData.nome || '',
        email: customerData.email || '',
        phone: cleanPhone || null,
        document: cleanCpf || null,
        country: 'BR'
      },
      products: cartItems.map((item, index) => ({
        id: item.id || `PROD-${index}`,
        name: item.name || 'Produto',
        planId: null,
        planName: null,
        quantity: item.qty || 1,
        priceInCents: Math.round((item.price || 0) * 100)
      })),
      trackingParameters: trackingParams,
      commission: {
        totalPriceInCents: totalPriceInCents,
        gatewayFeeInCents: gatewayFeeInCents,
        userCommissionInCents: userCommissionInCents
      },
      isTest: false
    };

    console.log('[Utmify] Enviando tracking:', status, payload);

    const response = await fetch('/api/utmify/track', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(payload)
    });

    const result = await response.json();
    console.log('[Utmify] Resposta:', response.status, result);

    if (!response.ok) {
      console.warn('[Utmify] Erro ao enviar tracking:', result);
    }

    return result;
  } catch (err) {
    console.error('[Utmify] Erro de tracking:', err);
    // Tracking não deve bloquear o fluxo de compra
    return null;
  }
}

function addToCart(productId, size, qty = 1) {
  const product = PRODUCTS.find(p => p.id === productId);
  if (!product) return;

  const existingItem = cart.find(item => item.id === productId && item.size === size);
  if (existingItem) {
    existingItem.qty += qty;
  } else {
    cart.push({
      id: productId,
      name: product.name,
      price: parsePrice(product.currentPrice),
      priceString: product.currentPrice,
      image: product.images[0],
      size: size,
      qty: qty
    });
  }
  saveCart();
  showToast(`Adicionado ao carrinho!`);

  // === META PIXEL: AddToCart ===
  if (typeof fbq === 'function') {
    fbq('track', 'AddToCart', {
      content_name: product.name,
      content_ids: [productId],
      content_type: 'product',
      value: parsePrice(product.currentPrice),
      currency: 'BRL'
    });
  }
}

function removeFromCart(productId, size) {
  cart = cart.filter(item => !(item.id === productId && item.size === size));
  saveCart();
  renderView(); // re-renderiza a view atual
}

function updateCartQty(productId, size, newQty) {
  const item = cart.find(item => item.id === productId && item.size === size);
  if (item) {
    item.qty = parseInt(newQty) || 1;
    if (item.qty <= 0) {
      removeFromCart(productId, size);
      return;
    }
  }
  saveCart();
  renderView();
}

function clearCart() {
  cart = [];
  saveCart();
}

function getCartSubtotal() {
  return cart.reduce((acc, item) => acc + (item.price * item.qty), 0);
}

function parsePrice(priceStr) {
  // Converte "R$ 149,90" -> 149.9
  const clean = priceStr.replace('R$', '').replace(/\s/g, '').replace('.', '').replace(',', '.');
  return parseFloat(clean) || 0;
}

function formatPrice(val) {
  return 'R$ ' + val.toFixed(2).replace('.', ',').replace(/\B(?=(\d{3})+(?!\d))/g, ".");
}

